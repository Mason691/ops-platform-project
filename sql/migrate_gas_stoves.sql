-- 燃具信息表（外部燃气系统 jinyuan_info.sb_gas_stoves_info 全量同步镜像）
-- gas_stoves_class 存平台字典 GAS_APPLIANCE_TYPE itemKey（1灶具 2热水器 3挂壁炉）
CREATE TABLE IF NOT EXISTS ops_gas_stoves_info (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    corp_id BIGINT NOT NULL DEFAULT 0 COMMENT '组织ID（同步触发组织；重复同步不覆盖）',
    batch_no VARCHAR(100) DEFAULT NULL COMMENT '同步批次号',
    remote_id VARCHAR(64) NOT NULL COMMENT '外部 sb_gas_stoves_info.id（去重键）',
    sb_gas_user_id VARCHAR(64) DEFAULT NULL COMMENT '燃气用户表ID（sb_gas_user.id = ops_gas_user.user_no，远程当前全为空）',
    t_gas_stoves_info_id VARCHAR(64) DEFAULT NULL COMMENT '燃气系统-燃具信息表ID',
    gas_stoves_class VARCHAR(20) DEFAULT NULL COMMENT '燃具种类（字典 GAS_APPLIANCE_TYPE itemKey：1灶具 2热水器 3挂壁炉）',
    gas_stoves_brand VARCHAR(64) DEFAULT NULL COMMENT '燃具品牌',
    gas_stoves_type VARCHAR(64) DEFAULT NULL COMMENT '燃具型号',
    `power` INT DEFAULT NULL COMMENT '功率',
    focal_eye VARCHAR(64) DEFAULT NULL COMMENT '灶眼',
    installation_time DATETIME DEFAULT NULL COMMENT '安装时间',
    startup_time DATETIME DEFAULT NULL COMMENT '启用时间',
    buy_time DATETIME DEFAULT NULL COMMENT '购买时间',
    installation_position CHAR(1) DEFAULT NULL COMMENT '安装位置（1厨房 2过道 3阳台 4其他）',
    user_number VARCHAR(64) DEFAULT NULL COMMENT '用户编号（远程值，对应 sb_gas_user.gas_supply_certificate_number）',
    gas_company_id VARCHAR(32) DEFAULT NULL COMMENT '燃气公司ID',
    gas_the_company_id VARCHAR(32) DEFAULT NULL COMMENT '燃气公司ID（系统侧）',
    user_id VARCHAR(32) DEFAULT NULL COMMENT '用户ID（远程）',
    gas_stoves_factory VARCHAR(100) DEFAULT NULL COMMENT '生产厂家',
    gas_stoves_num INT DEFAULT NULL COMMENT '燃具数量',
    -- BaseEntity fields（与 migrate_gas_user.sql 一致）
    update_key VARCHAR(50) DEFAULT NULL,
    unique_id VARCHAR(50) DEFAULT NULL,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    modify_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_user BIGINT DEFAULT NULL,
    modify_user BIGINT DEFAULT NULL,
    create_user_name VARCHAR(100) DEFAULT NULL,
    modify_user_name VARCHAR(100) DEFAULT NULL,
    sort INT DEFAULT 0,
    remark VARCHAR(500) DEFAULT NULL,
    delete_flag INT DEFAULT 0,
    UNIQUE KEY uk_remote_id (remote_id),
    INDEX idx_sb_gas_user (sb_gas_user_id),
    INDEX idx_corp (corp_id),
    INDEX idx_gas_stoves_class (gas_stoves_class)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='燃具信息表（外部燃气系统同步）';
