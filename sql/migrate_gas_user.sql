-- 燃气用户表 (广河公司 corp_id=10)
CREATE TABLE IF NOT EXISTS ops_gas_user (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    corp_id BIGINT NOT NULL DEFAULT 10 COMMENT '组织ID',
    community_id BIGINT DEFAULT NULL COMMENT '关联 sys_community.id',
    batch_no VARCHAR(100) DEFAULT NULL COMMENT '导入批次号',
    user_no VARCHAR(50) NOT NULL COMMENT '用户号',
    meter_no VARCHAR(50) DEFAULT NULL COMMENT '表号',
    user_name VARCHAR(100) DEFAULT NULL COMMENT '用户名',
    phone VARCHAR(20) DEFAULT NULL COMMENT '联系电话',
    area VARCHAR(255) DEFAULT NULL COMMENT '区域（原始地址描述）',
    address VARCHAR(255) DEFAULT NULL COMMENT '详细地址',
    status VARCHAR(50) DEFAULT NULL COMMENT '用户状态',
    balance DECIMAL(12,2) DEFAULT 0.00 COMMENT '余额',
    arrears DECIMAL(12,2) DEFAULT 0.00 COMMENT '欠费',
    open_time DATETIME DEFAULT NULL COMMENT '开户时间',
    -- BaseEntity fields
    update_key VARCHAR(50) DEFAULT NULL,
    unique_id VARCHAR(50) DEFAULT NULL,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    modify_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    create_user BIGINT DEFAULT NULL,
    modify_user BIGINT DEFAULT NULL,
    create_user_name VARCHAR(100) DEFAULT NULL,
    modify_user_name VARCHAR(100) DEFAULT NULL,
    sort INT DEFAULT 0,
    remark VARCHAR(500) DEFAULT NULL,
    delete_flag INT DEFAULT 0,
    UNIQUE KEY uk_user_corp (user_no, corp_id),
    INDEX idx_community (community_id),
    INDEX idx_corp (corp_id),
    INDEX idx_user_name (user_name),
    INDEX idx_phone (phone)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='燃气用户表';
